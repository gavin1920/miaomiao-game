def fp(pid, club, name, age, h, w, fl, fr, pos, tech, sp, mental, phys, hidden, traits=""):
    return _row(pid, name, club, age, h, w, fl, fr, pos, tech, sp, mental, phys, [""] * 12, hidden, traits)


def _row(pid, name, club, age, h, w, fl, fr, pos, tech, sp, mental, phys, g, hidden, traits=""):
    vals = [pid, name, club, age, h, w, fl, fr, pos] + list(tech) + list(sp) + list(mental) + list(phys) + list(g) + list(hidden) + [traits]
    assert len(vals) == 63, f"{pid}: {len(vals)}"
    return [str(v) for v in vals]


